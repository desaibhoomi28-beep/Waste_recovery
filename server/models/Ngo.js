const mongoose = require("mongoose");

const ngoSchema = new mongoose.Schema(
  {
    ngoName: {
      type: String,
      required: true,
    },

    contactPerson: {
      type: String,
      required: true,
    },

    email: {
      type: String,
      required: true,
      unique: true,
    },

    phone: {
      type: String,
      required: true,
    },

    address: {
      type: String,
      required: true,
    },

    acceptedWaste: [
      {
        type: String,
      },
    ],

    capacity: {
      type: Number,
      default: 0,
    },

    available: {
      type: Boolean,
      default: true,
    },
  },
  {
    timestamps: true,
  }
);

module.exports = mongoose.model("Ngo", ngoSchema);